// What If web components — plain custom elements, light DOM, styled by css/tokens.css + css/site.css.
//   <wi-mark size="40" [ink]>               the logo mark (inline SVG)
//   <wi-tag accent="red|blue|…">text</wi-tag>  a pill with an accent dot
//   <wi-episode-card number title duration accent cover src>  a 9:16 cover tile; activating it plays `src` in #player
export function markSVG(size = 40) {   // the unfinished-head mark (assets/brand, generated by tools/brand.mjs)
  return `<img src="assets/brand/theunfinishedco-mark.svg" width="${size}" height="${size}" alt="theunfinishedco" style="display:inline-block">`;
}

class WiMark extends HTMLElement {
  connectedCallback() { this.innerHTML = markSVG(Number(this.getAttribute('size') || 40), {ink: this.hasAttribute('ink')}); }
}
class WiTag extends HTMLElement {
  connectedCallback() { const a = this.getAttribute('accent'); if (a) this.style.setProperty('--tag-accent', `var(--wi-accent-${a})`); }
}
class WiEpisodeCard extends HTMLElement {
  connectedCallback() {
    const g = n => this.getAttribute(n) || '';
    const accent = g('accent') || 'red';
    this.style.setProperty('--ep-accent', `var(--wi-accent-${accent})`);
    this.innerHTML = `<button class="ep" type="button" aria-label="Play episode ${g('number')}: ${g('title').replace(/"/g, '&quot;')}">
      <span class="ep__cover"><img src="${g('cover')}" alt="" width="540" height="960">
        <span class="ep__num">#${g('number')}</span><span class="ep__dur">${Number(g('duration')).toFixed(0)} s</span>
        <span class="ep__play"><span></span></span></span>
      <span class="ep__title"><i aria-hidden="true"></i><span>${g('title')}</span></span></button>`;
    this.querySelector('button').addEventListener('click', () => this.dispatchEvent(new CustomEvent('wi-play', {bubbles: true, detail: {src: g('src'), title: g('title'), number: g('number')}})));
  }
}
customElements.define('wi-mark', WiMark);
customElements.define('wi-tag', WiTag);
customElements.define('wi-episode-card', WiEpisodeCard);
