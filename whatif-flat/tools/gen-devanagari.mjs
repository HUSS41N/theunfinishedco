#!/usr/bin/env node
// Pre-shaped Devanagari for the sets (owner: world). resvg's text shaping garbles Devanagari (matras move, conjuncts
// break), so every Hindi string the world paints is shaped once here with HarfBuzz (`hb-view`, brew install harfbuzz)
// and Hind Bold (tools/fonts, OFL), and written to src/devanagari.mjs as glyph outlines (font size 100, baseline y 0).
//   node tools/gen-devanagari.mjs          (add a string to STRINGS, re-run)
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url)), FONT = path.join(HERE, 'fonts', 'Hind-Bold.ttf');
const STRINGS = ['महिलाएँ', 'धूम्रपान निषेध', 'बिना टिकट यात्रा दंडनीय अपराध है', 'सिटी सेंटर', 'वरिष्ठ नागरिक', 'आपातकालीन द्वार', 'शुभ यात्रा', 'राज्य परिवहन', 'टिकट', 'अपने सामान की रक्षा स्वयं करें', 'चालक से बात न करें', 'ॐ'];
const glyphs = {}, strings = {};
const r1 = s => s.replace(/-?\d+\.\d+/g, v => String(+(+v).toFixed(1)));
for (const s of STRINGS) {
  const svg = execFileSync('hb-view', ['--output-format=svg', '--font-size=100', '--margin=0', FONT, s], {encoding: 'utf8'});
  const W = +/width="([\d.]+)"/.exec(svg)[1], local = {};
  for (const m of svg.matchAll(/<g id="(glyph-[\d-]+)">\s*<path d="([^"]*)"/g)) {
    const d = r1(m[2]).replace(/\s+/g, ' ').trim(); let k = Object.keys(glyphs).find(q => glyphs[q] === d); if (!k) { k = 'g' + Object.keys(glyphs).length; glyphs[k] = d; } local[m[1]] = k; }
  const uses = [...svg.matchAll(/<use xlink:href="#(glyph-[\d-]+)" x="([-\d.]+)" y="([-\d.]+)"/g)].map(m => [local[m[1]], +m[2], +m[3]]).filter(u => u[0]);
  const base = uses.length ? uses[0][2] : 0;
  strings[s] = {w: +W.toFixed(1), g: uses.map(([k, x, y]) => [k, +x.toFixed(1), +(y - base).toFixed(1)])};
}
const out = `// GENERATED by tools/gen-devanagari.mjs (HarfBuzz-shaped Hind Bold, OFL). Do not edit: add strings there and re-run.
// Glyph outlines at font size 100, baseline y 0. devanagari(text, x, y, {size, fill, anchor}) → svg.
const G = ${JSON.stringify(glyphs)};
const S = ${JSON.stringify(strings)};
export const DEVANAGARI = Object.keys(S);
/** a pre-shaped Devanagari string as outlines: x/y = the baseline anchor point; anchor 'start'|'middle'|'end' */
export function devanagari(text, x, y, {size = 40, fill = '#000', anchor = 'middle', opacity} = {}) {
  const s = S[text]; if (!s) throw new Error(\`devanagari: "\${text}" is not pre-shaped (add it to tools/gen-devanagari.mjs)\`);
  const k = size / 100, x0 = x - (anchor === 'middle' ? s.w * k / 2 : anchor === 'end' ? s.w * k : 0);
  const op = opacity !== undefined ? \` fill-opacity="\${+opacity.toFixed(3)}"\` : '';
  return \`<g transform="translate(\${+x0.toFixed(1)} \${+y.toFixed(1)}) scale(\${+k.toFixed(4)})" fill="\${fill}"\${op}>\` + s.g.map(([g, gx, gy]) => \`<path transform="translate(\${gx} \${gy})" d="\${G[g]}"/>\`).join('') + '</g>';
}
/** the advance width of a pre-shaped string at a font size */
export const devanagariWidth = (text, size = 40) => (S[text]?.w ?? 0) * size / 100;
`;
fs.writeFileSync(path.join(HERE, '..', 'src', 'devanagari.mjs'), out);
console.log(`src/devanagari.mjs: ${STRINGS.length} strings, ${Object.keys(glyphs).length} glyphs, ${(out.length / 1024).toFixed(1)} KB`);
